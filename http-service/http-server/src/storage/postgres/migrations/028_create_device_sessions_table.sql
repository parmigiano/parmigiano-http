CREATE TABLE IF NOT EXISTS device_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_uid BIGINT NOT NULL REFERENCES user_cores(user_uid) ON DELETE CASCADE,
    device_model VARCHAR(128) NOT NULL CHECK (length(btrim(device_model)) > 0), -- Модель устройства, exmp: MEGABOOK K16SDA
    platform VARCHAR(32) NOT NULL CHECK (length(btrim(platform)) > 0), -- Android, iOS, Windows, macOS, Linux, Web
    system_version VARCHAR(64) NOT NULL CHECK (length(btrim(system_version)) > 0), -- Версия ОС, exmp: Windows 11 x64
    app_version VARCHAR(64) NOT NULL CHECK (length(btrim(app_version)) > 0), -- Версия приложения, exmp: 7.0.1 x64
    date_created TIMESTAMPTZ NOT NULL DEFAULT now(), -- Когда выполнен вход
    date_active TIMESTAMPTZ NOT NULL DEFAULT now(), -- Последняя активность
    ip INET NOT NULL, -- Последний IP-адрес
    country VARCHAR(64), -- Страна по IP
    region VARCHAR(128), -- Регион или город по IP

    CHECK (date_active >= date_created)
);

CREATE INDEX IF NOT EXISTS idx_device_sessions_user_active ON device_sessions (user_uid, date_active DESC);

